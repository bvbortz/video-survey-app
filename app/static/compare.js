const QS = new URLSearchParams(location.search);
const LANG_KEY = "survey_lang", RATER_KEY = "survey_rater_id", SEEN_KEY = "compare_seen", ROUND_KEY = "compare_round";
let lang = "en";
try { const s = localStorage.getItem(LANG_KEY); if (s && I18N[s]) lang = s; } catch {}
if (I18N[QS.get("lang")]) lang = QS.get("lang");
let items = [], pos = 0, shownAt = 0, left = 0, round = 1;
const $ = (id) => document.getElementById(id);
const T = () => I18N[lang];

function raterId() {   // the survey's own per-browser id (app.js), so one person is one id
  try {
    let id = localStorage.getItem(RATER_KEY);
    if (!id) {
      id = (crypto.randomUUID && crypto.randomUUID()) ||
           ([1e7] + -1e3 + -4e3 + -8e3 + -1e11).replace(/[018]/g, c =>
             (c ^ crypto.getRandomValues(new Uint8Array(1))[0] & 15 >> c / 4).toString(16));
      localStorage.setItem(RATER_KEY, id);
    }
    return id;
  } catch { return null; }
}
function seen() { try { return new Set(JSON.parse(localStorage.getItem(SEEN_KEY) || "[]")); } catch { return new Set(); } }
function markSeen(id) { try { const s = seen(); s.add(id); localStorage.setItem(SEEN_KEY, JSON.stringify([...s])); } catch {} }

function el(tag, attrs = {}, ...kids) {
  const e = document.createElement(tag);
  for (const [k, v] of Object.entries(attrs)) k === "class" ? (e.className = v) : e.setAttribute(k, v);
  for (const k of kids) e.append(k);
  return e;
}

function setLang(l) {
  const refetch = items.length && (l === "ru") !== (lang === "ru");   // ru is served its own pairs
  lang = l;
  try { localStorage.setItem(LANG_KEY, l); } catch {}
  document.documentElement.lang = l;
  document.documentElement.dir = l === "he" ? "rtl" : "ltr";
  $("lang-en").classList.toggle("active", l === "en");
  $("lang-he").classList.toggle("active", l === "he");
  $("lang-ru").classList.toggle("active", l === "ru");
  $("title").textContent = T().title;
  $("rules-title").textContent = T().rulesTitle;
  $("rules-body").innerHTML = T().rules;
  if (refetch) load(); else if (items.length) show(); else $("msg").textContent = T().loading;
}

function header() {
  $("count").textContent = items.length ? T().counter(Math.min(pos + 1, items.length), items.length) : "";
  $("bar").style.width = items.length ? `${(100 * pos) / items.length}%` : "0";
}

function video(src) {
  const v = el("video", { src, controls: "", muted: "", autoplay: "", playsinline: "", loop: "", preload: "auto" });
  v.muted = true;
  return v;
}

function show() {
  header();
  const main = $("main");
  main.replaceChildren();
  if (pos >= items.length) return finished();
  const it = items[pos];
  const local = (lang === "he" && it.prompt_text_he) || (lang === "ru" && it.prompt_text_ru) || null;
  const he = lang === "he" && !!local;
  const vids = [video(it.first_url), video(it.second_url)];
  const note = el("textarea", { id: "note", rows: "2", placeholder: T().note });
  const flag = el("input", { type: "checkbox", id: "flag" });
  const btns = ["first", "same", "second"].map((v) => {
    const b = el("button", { type: "button", "data-v": v }, T()[v]);
    b.disabled = true;
    b.addEventListener("click", () => answer(it, v, note.value.trim(), flag.checked));
    return b;
  });
  const unlock = () => btns.forEach((b) => (b.disabled = false));
  const played = [false, false];
  vids.forEach((v, i) => v.addEventListener("timeupdate", () => {
    if (!played[i] && v.duration && v.currentTime > v.duration - 0.35) { played[i] = true; if (played[0] && played[1]) unlock(); }
  }));
  setTimeout(unlock, 25000);   // a stalled video must not trap the rater
  const replay = el("button", { type: "button", class: "replay" }, T().replay);
  replay.addEventListener("click", () => vids.forEach((v) => { v.currentTime = 0; v.play().catch(() => {}); }));
  main.append(
    el("div", { class: "prompt" },
      el("figure", {}, el("img", { src: it.image_url, alt: T().picture }), el("figcaption", {}, T().picture)),
      el("div", {},
        el("p", { class: "label" }, T().textLabel),
        el("p", { class: "ptext", dir: he ? "rtl" : "ltr" }, local || it.prompt_text),
        ...(local ? [el("p", { class: "ptext-en", dir: "ltr" }, it.prompt_text)] : []))),
    el("div", { class: "pair" },
      el("figure", {}, el("figcaption", { dir: "ltr" }, "A"), vids[0]),
      el("figure", {}, el("figcaption", { dir: "ltr" }, "B"), vids[1])),
    replay,
    el("div", { class: "verdicts" }, ...btns),
    el("p", { class: "hint" }, T().unlock),
    el("label", { class: "flag" }, flag, " ", T().flag),
    note);
  if (pos > 0) {
    const back = el("button", { type: "button", class: "back" }, T().back);
    back.addEventListener("click", () => { pos--; show(); });
    main.append(back);
  }
  shownAt = Date.now();
}

function answer(it, choice, note, promptFlag) {
  const body = { pair_id: it.pair_id, first: it.first, second: it.second, choice, note, prompt_flag: promptFlag,
                 elapsed_ms: Date.now() - shownAt, round, lang, rater_id: raterId() };
  const send = (n) => fetch("/api/compare/answer", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) })
    .then((r) => { if (!r.ok && r.status >= 500 && n > 0) throw new Error(r.status); })
    .catch(() => n > 0 && setTimeout(() => send(n - 1), 2000));
  send(3);
  markSeen(it.pair_id);
  pos++;
  if (pos === 1) $("rules").open = false;
  show();
}

function finished() {
  const main = $("main");
  main.append(el("p", { class: "ptext" }, left ? T().done : T().allDone));
  if (left) {
    main.append(el("p", {}, T().more(left)));
    const go = el("button", { type: "button", class: "primary" }, T().again);
    go.addEventListener("click", () => { round++; try { localStorage.setItem(ROUND_KEY, String(round)); } catch {} load(); });
    main.append(go);
  }
}

async function load() {
  items = []; pos = 0; header();
  $("main").replaceChildren(el("p", { class: "hint", id: "msg" }, T().loading));
  try {
    const q = new URLSearchParams({ rater: raterId() || "", seen: [...seen()].join(","), lang });
    const r = await fetch(`/api/compare/round?${q}`);
    if (!r.ok) throw new Error(r.status);
    const d = await r.json();
    items = d.items; left = d.left;
    show();
  } catch { $("main").replaceChildren(el("p", { class: "hint" }, T().error)); }
}

try { round = parseInt(localStorage.getItem(ROUND_KEY) || "1", 10) || 1; } catch {}
$("lang-en").addEventListener("click", () => setLang("en"));
$("lang-he").addEventListener("click", () => setLang("he"));
$("lang-ru").addEventListener("click", () => setLang("ru"));
setLang(lang);
load();
